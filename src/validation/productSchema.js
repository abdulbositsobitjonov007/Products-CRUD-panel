// ============================================================
// productSchema.js — Схема валидации данных продукта с Yup
//
// ЗАЧЕМ:
//   Yup описывает ПРАВИЛА для каждого поля формы.
//   React Hook Form проверяет данные по этим правилам
//   через yupResolver ДО отправки на сервер.
//   Если правило нарушено — форма не отправляется, а поле
//   получает сообщение об ошибке (errors.fieldName.message).
//
// ГДЕ ИСПОЛЬЗУЕТСЯ:
//   Импортируется в Products.jsx → передаётся в useForm({ resolver: yupResolver(productSchema) })
// ============================================================

import * as yup from "yup";

// yup.object().shape({}) — описываем объект, где каждый ключ — поле формы
export const productSchema = yup.object().shape({

  // ── Название продукта ────────────────────────────────────
  productName: yup
    .string()                                      // тип: строка
    .min(2, "Минимум 2 символа")                  // минимальная длина
    .max(100, "Максимум 100 символов")             // максимальная длина
    .required("Название обязательно"),            // нельзя оставлять пустым

  // ── Категория ────────────────────────────────────────────
  categoryId: yup
    .string()
    .required("Выберите категорию"),

  // ── Цена ─────────────────────────────────────────────────
  price: yup
    .number()
    .typeError("Цена должна быть числом")         // если ввели текст — эта ошибка
    .positive("Цена должна быть больше нуля")
    .required("Цена обязательна"),

  // ── Размер ───────────────────────────────────────────────
  size: yup
    .number()
    .typeError("Размер должен быть числом")
    .positive("Размер должен быть > 0")
    .required("Размер обязателен"),

  // ── Вес ──────────────────────────────────────────────────
  weight: yup
    .number()
    .typeError("Вес должен быть числом")
    .positive("Вес должен быть > 0")
    .required("Вес обязателен"),

  // ── Калории ──────────────────────────────────────────────
  calories: yup
    .number()
    .typeError("Калории должны быть числом")
    .min(0, "Калории не могут быть отрицательными")
    .required("Калории обязательны"),

  // ── Скидка (необязательная) ──────────────────────────────
  discount: yup
    .number()
    .typeError("Скидка должна быть числом")
    .min(0, "Скидка не может быть отрицательной")
    .max(100, "Скидка не может быть больше 100%")
    .default(0),                                  // по умолчанию 0 (не обязательна)

  // ── Рейтинг (необязательный) ─────────────────────────────
  rating: yup
    .number()
    .typeError("Рейтинг должен быть числом")
    .min(0, "Рейтинг не может быть < 0")
    .max(5, "Рейтинг не может быть > 5")
    .default(0),

  // ── URL изображения (необязательный) ─────────────────────
  productImg: yup
    .string()
    .url("Введите корректный URL изображения")    // проверяет формат https://...
    .nullable()                                    // разрешаем null
    .transform((v) => v || null),                 // пустую строку превращаем в null

  // ── Ингредиенты (строка через запятую) ───────────────────
  ingredients: yup
    .string()
    .nullable()
    .transform((v) => v || null),

  // ── Описание ─────────────────────────────────────────────
  productDescription: yup
    .string()
    .max(500, "Максимум 500 символов")
    .nullable()
    .transform((v) => v || null),

  // ── Булевые флаги (checkbox) — всегда true/false ─────────
  // yup.boolean() принимает значения true и false, не требует обязательности
  isSpicy:      yup.boolean().default(false),
  isPopular:    yup.boolean().default(false),
  isVegetarian: yup.boolean().default(false),
});
